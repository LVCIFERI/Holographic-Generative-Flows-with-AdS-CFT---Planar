def compute_nll(
    real_samples: np.ndarray,
    generated_samples: np.ndarray,
    n_pca_samples: int = 1000,
    n_components: int = 100,
) -> float:
    """
    Compute Negative Log-Likelihood using KDE with PCA preprocessing.
    
    This is a standard NLL metric for generative models that fits a KDE
    on the real data (in PCA space) and evaluates the likelihood of
    generated samples.
    
    Args:
        real_samples: (N, D) or (N, C, H, W) real samples
        generated_samples: (M, D) or (M, C, H, W) generated samples
        n_pca_samples: Number of real samples to use for PCA fitting
        n_components: Number of PCA components
        
    Returns:
        Negative log-likelihood (lower is better)
        
    Note:
        Returns infinity if computation fails.
    """
    if not SKLEARN_AVAILABLE or not SCIPY_AVAILABLE:
        print("Warning: sklearn or scipy not available for NLL computation")
        return float('inf')
    
    # Flatten to (N, D)
    real_samples = real_samples.reshape(real_samples.shape[0], -1)
    generated_samples = generated_samples.reshape(generated_samples.shape[0], -1)
    
    # Subsample real data for PCA fitting
    n_samples = min(n_pca_samples, real_samples.shape[0])
    rng = np.random.default_rng(42)
    idx = rng.choice(real_samples.shape[0], n_samples, replace=False)
    real_subset = real_samples[idx]
    
    # Determine number of PCA components
    n_components = min(n_components, real_subset.shape[1], n_samples - 1)
    
    try:
        # Fit PCA on real data
        pca = PCA(n_components=n_components, svd_solver='full')
        real_subset_pca = pca.fit_transform(real_subset)
        generated_samples_pca = pca.transform(generated_samples)
        
        # Check explained variance
        explained_variance_ratio = np.sum(pca.explained_variance_ratio_)
        if explained_variance_ratio < 0.8:
            print(f"Warning: PCA captured only {explained_variance_ratio:.4f} of variance")
        
        # Fit KDE on real data in PCA space
        kde = gaussian_kde(real_subset_pca.T)
        
        # Evaluate log-likelihood of generated samples
        log_likelihood = np.mean(kde.logpdf(generated_samples_pca.T))
        
        return float(-log_likelihood)
        
    except np.linalg.LinAlgError as e:
        print(f"KDE computation failed after PCA: {e}")
        return float('inf')
    except Exception as e:
        print(f"Error in NLL computation: {e}")
        return float('inf')


def compute_fid(
    real_images: Tensor,
    generated_images: Tensor,
    batch_size: int = 50,
    device: Optional[str] = None,
    dims: int = 2048,
) -> float:
    """
    Compute Fréchet Inception Distance (FID) for image data.
    
    FID measures the distance between feature distributions of real and
    generated images using InceptionV3. Lower is better.
    
    For grayscale images (e.g., MNIST), channels are repeated 3 times and
    images are resized to 299x299 for InceptionV3.
    
    Args:
        real_images: (N, C, H, W) or (N, H, W) or (N, D) real images in [0, 1]
        generated_images: (M, C, H, W) or (M, H, W) or (M, D) generated images in [0, 1]
        batch_size: Batch size for InceptionV3 forward pass
        device: Device to use (defaults to CUDA if available)
        dims: Feature dimensionality (2048 for pool3 layer)
        
    Returns:
        FID score (lower is better)
        
    Note:
        Returns -1 if torchvision is not available.
    """
    if not TORCHVISION_AVAILABLE:
        print("Warning: torchvision not available for FID computation")
        return -1.0
    
    if device is None:
        device = 'cuda' if torch.cuda.is_available() else 'cpu'
    
    # Convert numpy to tensor if needed
    if isinstance(real_images, np.ndarray):
        real_images = torch.from_numpy(real_images).float()
    if isinstance(generated_images, np.ndarray):
        generated_images = torch.from_numpy(generated_images).float()
    
    real_images = real_images.float()
    generated_images = generated_images.float()
    
    # Handle flattened images (e.g., MNIST as 784-dim vectors)
    # Detect MNIST: 784 = 28*28, Fashion-MNIST same
    if real_images.ndim == 2:
        d = real_images.shape[1]
        if d == 784:  # MNIST/Fashion-MNIST
            real_images = real_images.view(-1, 1, 28, 28)
            generated_images = generated_images.view(-1, 1, 28, 28)
        elif d == 3072:  # CIFAR (32*32*3)
            real_images = real_images.view(-1, 3, 32, 32)
            generated_images = generated_images.view(-1, 3, 32, 32)
        else:
            # Try to infer square image size
            h = int(np.sqrt(d))
            if h * h == d:
                real_images = real_images.view(-1, 1, h, h)
                generated_images = generated_images.view(-1, 1, h, h)
            else:
                print(f"Warning: Cannot infer image shape from {d}-dim vectors")
                return -1.0
    
    # Handle 3D tensors (N, H, W) -> (N, 1, H, W)
    if real_images.ndim == 3:
        real_images = real_images.unsqueeze(1)
    if generated_images.ndim == 3:
        generated_images = generated_images.unsqueeze(1)
    
    # Get image dimensions
    n_real, c_real, h_real, w_real = real_images.shape
    n_gen, c_gen, h_gen, w_gen = generated_images.shape
    
    # Load InceptionV3 model
    try:
        inception = tv_models.inception_v3(weights='IMAGENET1K_V1', transform_input=False)
        inception.fc = torch.nn.Identity()  # Remove classification layer
        inception = inception.to(device).eval()
    except Exception as e:
        print(f"Failed to load InceptionV3: {e}")
        return -1.0
    
    def preprocess_batch(images: Tensor) -> Tensor:
        """Preprocess images for InceptionV3."""
        # Ensure 4D: (N, C, H, W)
        if images.ndim == 3:
            images = images.unsqueeze(1)
        
        n, c, h, w = images.shape
        
        # Convert grayscale to RGB by repeating channels
        if c == 1:
            images = images.repeat(1, 3, 1, 1)
        
        # Resize to 299x299 (InceptionV3 input size)
        if h != 299 or w != 299:
            images = torch.nn.functional.interpolate(
                images, size=(299, 299), mode='bilinear', align_corners=False
            )
        
        # ImageNet normalization
        mean = torch.tensor([0.485, 0.456, 0.406], device=images.device).view(1, 3, 1, 1)
        std = torch.tensor([0.229, 0.224, 0.225], device=images.device).view(1, 3, 1, 1)
        images = (images - mean) / std
        
        return images
    
    def get_activations(images: Tensor) -> np.ndarray:
        """Extract InceptionV3 features."""
        n_batches = (images.shape[0] + batch_size - 1) // batch_size
        activations = []
        
        for i in range(n_batches):
            start = i * batch_size
            end = min((i + 1) * batch_size, images.shape[0])
            batch = images[start:end].to(device)
            batch = preprocess_batch(batch)
            
            with torch.no_grad():
                # InceptionV3 returns (output, aux) in training mode
                # In eval mode, it returns just output
                act = inception(batch)
                if isinstance(act, tuple):
                    act = act[0]
            
            # Global average pooling if spatial dimensions remain
            if act.ndim == 4 and (act.shape[2] != 1 or act.shape[3] != 1):
                act = torch.nn.functional.adaptive_avg_pool2d(act, (1, 1))
            
            act = act.view(act.shape[0], -1)
            activations.append(act.cpu().numpy())
        
        return np.concatenate(activations, axis=0)
    
    try:
        # Get activations
        act_real = get_activations(real_images)
        act_gen = get_activations(generated_images)
        
        # Compute statistics
        mu_real = np.mean(act_real, axis=0)
        sigma_real = np.cov(act_real, rowvar=False)
        mu_gen = np.mean(act_gen, axis=0)
        sigma_gen = np.cov(act_gen, rowvar=False)
        
        # Handle single sample case
        if sigma_real.ndim == 0:
            sigma_real = np.array([[sigma_real]])
        if sigma_gen.ndim == 0:
            sigma_gen = np.array([[sigma_gen]])
        
        # Compute FID: ||mu_1 - mu_2||^2 + Tr(sigma_1 + sigma_2 - 2*sqrt(sigma_1 @ sigma_2))
        diff = mu_real - mu_gen
        mean_term = np.dot(diff, diff)
        
        # Matrix square root
        covmean, _ = linalg.sqrtm(sigma_real @ sigma_gen, disp=False)
        
        # Handle numerical issues
        if not np.isfinite(covmean).all():
            eps = 1e-6
            offset = np.eye(sigma_real.shape[0]) * eps
            covmean = linalg.sqrtm((sigma_real + offset) @ (sigma_gen + offset))
        
        # Take real part if complex
        if np.iscomplexobj(covmean):
            covmean = covmean.real
        
        cov_term = np.trace(sigma_real + sigma_gen - 2 * covmean)
        
        fid = float(mean_term + cov_term)
        
        return max(0.0, fid)  # FID should be non-negative
        
    except Exception as e:
        print(f"Error in FID computation: {e}")
        return -1.0


def sliced_wasserstein_distance(
    real: Tensor,
    gen: Tensor,
    n_projections: int = 1000,
) -> float:
    """
    Sliced Wasserstein Distance for images.

    Projects high-dimensional data onto random 1D directions and
    computes average 1D Wasserstein distance. This is a fast
    approximation to the true Wasserstein distance.

    Args:
        real: (N, C, H, W) or (N, D) real samples
        gen: (M, C, H, W) or (M, D) generated samples
        n_projections: Number of random projections

    Returns:
        SWD estimate

    Example
    -------
    >>> swd = sliced_wasserstein_distance(real_images, gen_images)
    """
    # Flatten if needed
    if real.ndim > 2:
        real = real.view(real.shape[0], -1)
    if gen.ndim > 2:
        gen = gen.view(gen.shape[0], -1)

    real = real.float().cpu()
    gen = gen.float().cpu()

    d = real.shape[1]

    # Random projection directions (unit vectors)
    directions = torch.randn(n_projections, d)
    directions = directions / directions.norm(dim=1, keepdim=True)

    # Project data
    real_proj = real @ directions.T  # (N, n_proj)
    gen_proj = gen @ directions.T  # (M, n_proj)

    # Sort projections
    real_sorted = torch.sort(real_proj, dim=0)[0]
    gen_sorted = torch.sort(gen_proj, dim=0)[0]

    # Handle different sample sizes by interpolation
    n, m = real_sorted.shape[0], gen_sorted.shape[0]
    if n != m:
        # Interpolate to same size
        size = min(n, m)
        real_idx = torch.linspace(0, n - 1, size).long()
        gen_idx = torch.linspace(0, m - 1, size).long()
        real_sorted = real_sorted[real_idx]
        gen_sorted = gen_sorted[gen_idx]

    # Compute 1D Wasserstein (L2 distance between sorted samples)
    swd = (real_sorted - gen_sorted).pow(2).mean(dim=0).sqrt().mean()

    return float(swd)


