def compute_energy_distance(x: Tensor, y: Tensor) -> float:
    """
    Compute energy distance between two distributions.

    Energy distance is an alternative to MMD that is based on
    Euclidean distances rather than kernel evaluations.

    Args:
        x: (N, D) samples from P
        y: (M, D) samples from Q

    Returns:
        Energy distance

    Example
    -------
    >>> ed = compute_energy_distance(real, gen)
    """
    x = x.float()
    y = y.float()

    # Pairwise distances
    xx = torch.cdist(x, x, p=2).mean()
    yy = torch.cdist(y, y, p=2).mean()
    xy = torch.cdist(x, y, p=2).mean()

    # Energy distance formula
    ed = 2 * xy - xx - yy

    return float(max(0.0, ed))


def compute_frechet_distance(
    mu1: Tensor,
    sigma1: Tensor,
    mu2: Tensor,
    sigma2: Tensor,
    eps: float = 1e-6,
) -> float:
    """
    Compute Fréchet distance between two Gaussian distributions.

    This is the building block for FID (Fréchet Inception Distance).

    FD(μ₁, Σ₁, μ₂, Σ₂) = ||μ₁ - μ₂||² + Tr(Σ₁ + Σ₂ - 2(Σ₁Σ₂)^{1/2})

    Args:
        mu1: Mean of first distribution
        sigma1: Covariance of first distribution
        mu2: Mean of second distribution
        sigma2: Covariance of second distribution
        eps: Small constant for numerical stability

    Returns:
        Fréchet distance
    """
    if not SCIPY_AVAILABLE:
        return -1.0

    mu1 = mu1.cpu().numpy()
    sigma1 = sigma1.cpu().numpy()
    mu2 = mu2.cpu().numpy()
    sigma2 = sigma2.cpu().numpy()

    # Mean difference
    diff = mu1 - mu2
    mean_term = diff @ diff

    # Covariance term
    covmean, _ = linalg.sqrtm(sigma1 @ sigma2, disp=False)

    # Handle numerical issues
    if not np.isfinite(covmean).all():
        offset = np.eye(sigma1.shape[0]) * eps
        covmean = linalg.sqrtm((sigma1 + offset) @ (sigma2 + offset))

    if np.iscomplexobj(covmean):
        covmean = covmean.real

    cov_term = np.trace(sigma1 + sigma2 - 2 * covmean)

    return float(mean_term + cov_term)


def compute_log_likelihood_estimate(
    samples: Tensor,
    reference_samples: Tensor,
    bandwidth: Optional[float] = None,
) -> float:
    """
    Estimate log-likelihood using kernel density estimation.

    This provides a rough estimate of how well the generated samples
    fit the reference distribution.

    Args:
        samples: Samples to evaluate
        reference_samples: Reference samples defining the distribution
        bandwidth: KDE bandwidth (if None, uses Scott's rule)

    Returns:
        Average log-likelihood estimate
    """
    samples = samples.float()
    reference_samples = reference_samples.float()

    n_ref = reference_samples.shape[0]
    d = samples.shape[1]

    # Scott's rule for bandwidth
    if bandwidth is None:
        bandwidth = n_ref ** (-1 / (d + 4)) * reference_samples.std()
        bandwidth = max(bandwidth, 1e-3)

    # Compute pairwise distances
    dists = torch.cdist(samples, reference_samples, p=2)

    # Gaussian kernel density estimate
    log_kernels = -0.5 * (dists / bandwidth) ** 2
    log_density = torch.logsumexp(log_kernels, dim=1) - np.log(n_ref)
    log_density -= d / 2 * np.log(2 * np.pi) + d * np.log(bandwidth)

    return float(log_density.mean())


