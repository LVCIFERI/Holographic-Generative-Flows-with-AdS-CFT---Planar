def checkerboard_valid_mask(Nx: int, Ny: int, parity: int = 0) -> np.ndarray:
    """
    Create a boolean mask for valid checkerboard cells.
    
    Args:
        Nx: Number of cells in x direction
        Ny: Number of cells in y direction
        parity: 0 or 1, determines which tiles are valid
        
    Returns:
        (Nx, Ny) boolean array where True indicates a valid cell
    """
    ii = np.arange(Nx)[:, None]
    jj = np.arange(Ny)[None, :]
    return ((ii + jj) % 2) == parity


def points_to_cells(
    X: np.ndarray,
    xmin: float,
    ymin: float,
    cell_size: float,
    Nx: int,
    Ny: int,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Map points to cell indices and determine in-domain status.
    
    Args:
        X: (N, 2) array of points
        xmin: Minimum x coordinate of domain
        ymin: Minimum y coordinate of domain
        cell_size: Size of each cell
        Nx: Number of cells in x direction
        Ny: Number of cells in y direction
        
    Returns:
        i: (N,) cell x-indices (clamped to valid range)
        j: (N,) cell y-indices (clamped to valid range)
        in_domain: (N,) boolean mask for points within the domain
    """
    x, y = X[:, 0], X[:, 1]
    
    # Check if points are within domain bounds
    xmax = xmin + Nx * cell_size
    ymax = ymin + Ny * cell_size
    in_domain = (x >= xmin) & (x < xmax) & (y >= ymin) & (y < ymax)
    
    # Compute cell indices
    i = np.floor((x - xmin) / cell_size).astype(int)
    j = np.floor((y - ymin) / cell_size).astype(int)
    
    # Clamp indices for safe indexing (out-of-domain handled by in_domain mask)
    i = np.clip(i, 0, Nx - 1)
    j = np.clip(j, 0, Ny - 1)
    
    return i, j, in_domain


def js_divergence(p: np.ndarray, q: np.ndarray, eps: float = 1e-12) -> float:
    """
    Compute Jensen-Shannon divergence between two probability distributions.
    
    JS(p, q) = 0.5 * KL(p || m) + 0.5 * KL(q || m), where m = 0.5 * (p + q)
    
    Args:
        p: First probability distribution (must sum to 1)
        q: Second probability distribution (must sum to 1)
        eps: Small constant for numerical stability
        
    Returns:
        JS divergence (in [0, log(2)] for natural log)
    """
    # Ensure non-negative and normalized
    p = np.clip(p, eps, 1.0)
    q = np.clip(q, eps, 1.0)
    p = p / p.sum()
    q = q / q.sum()
    
    m = 0.5 * (p + q)
    
    # KL divergences
    kl_pm = np.sum(p * (np.log(p) - np.log(m)))
    kl_qm = np.sum(q * (np.log(q) - np.log(m)))
    
    return 0.5 * (kl_pm + kl_qm)


def energy_distance_unbiased(X: np.ndarray, Y: np.ndarray) -> float:
    """
    Compute unbiased estimator of energy distance between two point sets.
    
    ED²(P, Q) = 2*E||X - Y|| - E||X - X'|| - E||Y - Y'||
    
    Uses unbiased U-statistic estimator (excludes diagonal terms).
    
    Args:
        X: (n, 2) samples from distribution P
        Y: (m, 2) samples from distribution Q
        
    Returns:
        Energy distance (ED, not squared), or NaN if insufficient points
    """
    n, m = len(X), len(Y)
    
    if n < 2 or m < 2:
        return np.nan
    
    # Pairwise distances
    d_xy = np.linalg.norm(X[:, None, :] - Y[None, :, :], axis=-1)  # (n, m)
    d_xx = np.linalg.norm(X[:, None, :] - X[None, :, :], axis=-1)  # (n, n)
    d_yy = np.linalg.norm(Y[:, None, :] - Y[None, :, :], axis=-1)  # (m, m)
    
    term_xy = 2.0 * d_xy.mean()
    
    # Unbiased within-distribution terms (exclude diagonal)
    term_xx = (d_xx.sum() - np.trace(d_xx)) / (n * (n - 1))
    term_yy = (d_yy.sum() - np.trace(d_yy)) / (m * (m - 1))
    
    ed2 = term_xy - term_xx - term_yy
    ed2 = max(ed2, 0.0)  # Numerical safety
    
    return np.sqrt(ed2)


def compute_checkerboard_metrics(
    X_real: np.ndarray,
    X_gen: np.ndarray,
    domain: Tuple[float, float, float, float] = (-4.0, 4.0, -4.0, 4.0),
    cell_size: float = 1.0,
    parity: int = 0,
    alpha: float = 1e-6,
    min_points_cell: int = 5,
    max_points_cell: Optional[int] = None,
    lam: float = 1.0,
    mu: float = 1.0,
) -> Dict[str, float]:
    """
    Compute checkerboard-specific quality metrics.
    
    Computes four metrics:
    1. BV (Boundary Violation): Fraction of generated points outside valid cells
    2. JS_cell: Jensen-Shannon divergence of cell occupancy distributions
    3. WED (Within-cell Energy Distance): Weighted average ED inside cells
    4. CQS (Checkerboard Quality Score): Composite metric = JS + λ*BV + μ*WED_norm
    
    Args:
        X_real: (N, 2) real samples
        X_gen: (M, 2) generated samples
        domain: (xmin, xmax, ymin, ymax) bounding box
        cell_size: Size of each checkerboard cell
        parity: 0 or 1, determines which tiles are valid
        alpha: Dirichlet smoothing for histogram (prevents log(0))
        min_points_cell: Minimum real points in cell to compute ED
        max_points_cell: Optional cap on points per cell for speed
        lam: Weight for BV in CQS
        mu: Weight for WED_norm in CQS
        
    Returns:
        Dictionary containing:
        - BV: Boundary violation rate [0, 1]
        - JS_cell: Cell occupancy JS divergence [0, log(2)]
        - WED: Weighted within-cell energy distance
        - WED_norm: WED normalized by cell_size
        - CQS: Composite quality score (lower is better)
        - Nx, Ny: Number of cells in each direction
        - num_valid_cells: Number of valid checkerboard cells
        - real_valid_frac: Fraction of real points in valid cells
        - gen_valid_frac: Fraction of generated points in valid cells
    """
    xmin, xmax, ymin, ymax = domain
    Nx = int(np.floor((xmax - xmin) / cell_size))
    Ny = int(np.floor((ymax - ymin) / cell_size))
    
    # Create valid cell mask
    valid = checkerboard_valid_mask(Nx, Ny, parity=parity)
    
    # Map points to cells
    ir, jr, inr = points_to_cells(X_real, xmin, ymin, cell_size, Nx, Ny)
    ig, jg, ing = points_to_cells(X_gen, xmin, ymin, cell_size, Nx, Ny)
    
    # Validity of each point (in-domain AND in valid cell)
    real_valid = inr & valid[ir, jr]
    gen_valid = ing & valid[ig, jg]
    
    # =========================================================================
    # 1) Boundary Violation (BV)
    # =========================================================================
    BV = 1.0 - gen_valid.mean()
    
    # =========================================================================
    # 2) Cell Occupancy JS Divergence
    # =========================================================================
    # Build list of valid cell indices
    valid_cells = np.argwhere(valid)  # (V, 2) with [i, j]
    V = len(valid_cells)
    
    # Map (i, j) -> linear valid-cell id
    id_map = -np.ones((Nx, Ny), dtype=int)
    id_map[valid] = np.arange(V)
    
    # Get valid-cell IDs for valid points
    rid = id_map[ir[real_valid], jr[real_valid]]
    gid = id_map[ig[gen_valid], jg[gen_valid]]
    
    # Count points per valid cell with Dirichlet smoothing
    pr_counts = np.bincount(rid, minlength=V).astype(float) + alpha
    pg_counts = np.bincount(gid, minlength=V).astype(float) + alpha
    
    # Normalize to probability distributions
    pr = pr_counts / pr_counts.sum()
    pg = pg_counts / pg_counts.sum()
    
    JS_cell = js_divergence(pr, pg)
    
    # =========================================================================
    # 3) Within-cell Energy Distance (weighted by real occupancy)
    # =========================================================================
    # Collect indices per valid cell
    real_by_cell = [[] for _ in range(V)]
    gen_by_cell = [[] for _ in range(V)]
    
    real_idx = np.where(real_valid)[0]
    gen_idx = np.where(gen_valid)[0]
    
    for idx in real_idx:
        cid = id_map[ir[idx], jr[idx]]
        real_by_cell[cid].append(idx)
    
    for idx in gen_idx:
        cid = id_map[ig[idx], jg[idx]]
        gen_by_cell[cid].append(idx)
    
    ed_list = []
    w_list = []
    
    for c in range(V):
        r_idx = real_by_cell[c]
        g_idx = gen_by_cell[c]
        
        # Skip cells with too few real points
        if len(r_idx) < min_points_cell:
            continue
        
        # Skip cells with too few generated points (let JS capture this)
        if len(g_idx) < 2:
            continue
        
        Xc = X_real[np.array(r_idx)]
        Yc = X_gen[np.array(g_idx)]
        
        # Optional cap on points per cell for speed
        if max_points_cell is not None:
            if len(Xc) > max_points_cell:
                idx_sample = np.random.choice(len(Xc), max_points_cell, replace=False)
                Xc = Xc[idx_sample]
            if len(Yc) > max_points_cell:
                idx_sample = np.random.choice(len(Yc), max_points_cell, replace=False)
                Yc = Yc[idx_sample]
        
        ed = energy_distance_unbiased(Xc, Yc)
        
        if np.isnan(ed):
            continue
        
        # Weight by real cell probability
        w = pr[c]
        ed_list.append(ed)
        w_list.append(w)
    
    if len(ed_list) == 0:
        WED = np.nan
        WED_norm = np.nan
    else:
        w = np.array(w_list)
        w = w / w.sum()  # Re-normalize weights
        WED = float(np.sum(w * np.array(ed_list)))
        WED_norm = WED / cell_size  # Dimensionless
    
    # =========================================================================
    # 4) Composite Checkerboard Quality Score (CQS)
    # =========================================================================
    CQS = JS_cell + lam * BV + (mu * WED_norm if not np.isnan(WED_norm) else 0.0)
    
    return {
        "BV": float(BV),
        "JS_cell": float(JS_cell),
        "WED": float(WED) if not np.isnan(WED) else None,
        "WED_norm": float(WED_norm) if not np.isnan(WED_norm) else None,
        "CQS": float(CQS),
        "Nx": Nx,
        "Ny": Ny,
        "num_valid_cells": V,
        "real_valid_frac": float(real_valid.mean()),
        "gen_valid_frac": float(gen_valid.mean()),
    }


