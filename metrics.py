def wasserstein_1d_w2(x: np.ndarray, y: np.ndarray) -> float:
    """
    Compute 1D Wasserstein-2 distance.

    For 1D distributions, W2 = sqrt(mean((sort(x) - sort(y))^2)).
    This is the closed-form solution for 1D optimal transport with L2 cost.

    Args:
        x: First set of samples (N,)
        y: Second set of samples (M,)

    Returns:
        1D Wasserstein-2 distance
    """
    x = np.sort(x.flatten())
    y = np.sort(y.flatten())
    
    # Handle different sample sizes by interpolation
    n, m = len(x), len(y)
    if n != m:
        # Interpolate to same size
        size = min(n, m)
        x_idx = np.linspace(0, n - 1, size).astype(int)
        y_idx = np.linspace(0, m - 1, size).astype(int)
        x = x[x_idx]
        y = y[y_idx]
    
    return np.sqrt(np.mean((x - y) ** 2))


def sliced_wasserstein_2d(real: np.ndarray, gen: np.ndarray, n_projections: int = 100) -> float:
    """
    Sliced Wasserstein-2 distance for 2D point clouds.

    Projects onto random 1D directions and computes average 1D W2.
    This is a fast approximation to the true 2D Wasserstein-2 distance.

    Args:
        real: (N, 2) real samples
        gen: (M, 2) generated samples
        n_projections: Number of random projections

    Returns:
        Sliced W2 distance
    """
    # Random projection directions
    theta = np.linspace(0, np.pi, n_projections, endpoint=False)
    directions = np.stack([np.cos(theta), np.sin(theta)], axis=1)  # (n_proj, 2)

    # Project and compute 1D W2
    distances = []
    for d in directions:
        proj_real = real @ d  # (N,)
        proj_gen = gen @ d  # (M,)
        distances.append(wasserstein_1d_w2(proj_real, proj_gen))

    return np.mean(distances)


def wasserstein_2d_exact(real: np.ndarray, gen: np.ndarray) -> float:
    """
    Exact Wasserstein-2 distance using POT (Python Optimal Transport).

    Computes the true optimal transport distance with squared Euclidean cost.
    This is slower than sliced W2 but exact.

    Args:
        real: (N, D) real samples
        gen: (M, D) generated samples

    Returns:
        Exact W2 distance, or -1 if POT unavailable
    """
    if not POT_AVAILABLE:
        return -1.0
    
    n, m = len(real), len(gen)
    
    # Uniform weights
    a = np.ones(n) / n
    b = np.ones(m) / m
    
    # Cost matrix (squared Euclidean distances)
    M = ot.dist(real, gen, metric='sqeuclidean')
    
    # Compute W2^2 using EMD
    w2_squared = ot.emd2(a, b, M)
    
    return np.sqrt(w2_squared)


def wasserstein_2d(real: np.ndarray, gen: np.ndarray) -> float:
    """
    Compute 2D Wasserstein-2 distance.

    Uses exact W2 if POT is available and sample size is reasonable,
    otherwise falls back to sliced W2.

    Args:
        real: (N, 2) real samples
        gen: (M, 2) generated samples

    Returns:
        W2 distance
    """
    n, m = len(real), len(gen)
    
    # Use exact W2 if POT is available (up to 15k samples)
    if POT_AVAILABLE and n <= 15000 and m <= 15000:
        return wasserstein_2d_exact(real, gen)
    else:
        return sliced_wasserstein_2d(real, gen)


def compute_mmd(
    x: Tensor,
    y: Tensor,
    kernel: str = "rbf",
    sigma: Optional[float] = None,
) -> float:
    """
    Maximum Mean Discrepancy between two distributions.

    MMD is a kernel-based distance metric that measures the difference
    between two probability distributions in a reproducing kernel
    Hilbert space (RKHS).

    Args:
        x: (N, D) samples from distribution P
        y: (M, D) samples from distribution Q
        kernel: Kernel type ('rbf' or 'linear')
        sigma: RBF kernel bandwidth (if None, uses median heuristic)

    Returns:
        MMD estimate (non-negative)

    Example
    -------
    >>> x = torch.randn(1000, 2)  # samples from P
    >>> y = torch.randn(1000, 2) + 0.5  # samples from Q (shifted)
    >>> mmd = compute_mmd(x, y)
    """
    x = x.float()
    y = y.float()

    # Median heuristic for bandwidth if not specified
    if sigma is None and kernel == "rbf":
        with torch.no_grad():
            dists = torch.cdist(x, y, p=2)
            sigma = float(dists.median())
            if sigma < 1e-6:
                sigma = 1.0

    def rbf_kernel(a: Tensor, b: Tensor, sigma: float) -> Tensor:
        dist_sq = torch.cdist(a, b, p=2) ** 2
        return torch.exp(-dist_sq / (2 * sigma ** 2))

    if kernel == "rbf":
        k_xx = rbf_kernel(x, x, sigma)
        k_yy = rbf_kernel(y, y, sigma)
        k_xy = rbf_kernel(x, y, sigma)
    else:  # linear kernel
        k_xx = x @ x.T
        k_yy = y @ y.T
        k_xy = x @ y.T

    n, m = x.shape[0], y.shape[0]

    # Unbiased estimate of MMD²
    mmd = (k_xx.sum() - k_xx.trace()) / (n * (n - 1))
    mmd += (k_yy.sum() - k_yy.trace()) / (m * (m - 1))
    mmd -= 2 * k_xy.mean()

    # MMD² can be slightly negative due to finite sample bias; clamp to 0
    return float(max(0.0, mmd))


def compute_mmd_multiscale(x: Tensor, y: Tensor) -> float:
    """
    Multi-scale MMD using multiple RBF bandwidths.

    More robust than single-bandwidth MMD as it captures
    both fine and coarse distribution differences.

    Uses bandwidths at [0.1, 0.5, 1.0, 2.0, 10.0] × median distance.

    Args:
        x: (N, D) samples from P
        y: (M, D) samples from Q

    Returns:
        Multi-scale MMD estimate (non-negative)

    Example
    -------
    >>> mmd = compute_mmd_multiscale(real_samples, gen_samples)
    """
    x = x.float()
    y = y.float()

    # Compute median distance for scale reference
    with torch.no_grad():
        dists = torch.cdist(x, y, p=2)
        median_dist = float(dists.median())
        if median_dist < 1e-6:
            median_dist = 1.0

    # Multiple bandwidths around the median
    sigmas = [median_dist * scale for scale in [0.1, 0.5, 1.0, 2.0, 10.0]]

    mmd_total = 0.0
    for sigma in sigmas:
        mmd_total += compute_mmd(x, y, kernel="rbf", sigma=sigma)

    return mmd_total / len(sigmas)


def compute_coverage_density(
    real: Tensor,
    gen: Tensor,
    k: int = 5,
) -> Tuple[float, float]:
    """
    Coverage and Density metrics using k-NN.

    Coverage: fraction of real samples with a generated neighbor within threshold
    Density: average number of generated samples near each real sample

    The threshold is computed as the median k-NN distance in the real data.

    Args:
        real: (N, D) real samples
        gen: (M, D) generated samples
        k: Number of nearest neighbors

    Returns:
        Tuple of (coverage, density), or (-1, -1) if scipy unavailable

    Example
    -------
    >>> coverage, density = compute_coverage_density(real, gen, k=5)
    >>> print(f"Coverage: {coverage:.2%}, Density: {density:.4f}")
    """
    if not SCIPY_AVAILABLE:
        return -1.0, -1.0

    real_np = real.cpu().numpy()
    gen_np = gen.cpu().numpy()

    # Build KD-trees
    real_tree = cKDTree(real_np)
    gen_tree = cKDTree(gen_np)

    # Compute threshold as median k-NN distance in real data
    real_dists, _ = real_tree.query(real_np, k=k + 1)  # +1 because self is included
    threshold = np.median(real_dists[:, -1])

    # Coverage: fraction of real samples with a generated neighbor within threshold
    real_to_gen_dists, _ = gen_tree.query(real_np, k=1)
    coverage = (real_to_gen_dists < threshold).mean()

    # Density: avg generated samples within threshold of real
    real_to_gen_counts = gen_tree.query_ball_point(real_np, threshold)
    density = np.mean([len(c) for c in real_to_gen_counts]) / len(gen_np)

    return float(coverage), float(density)


def compute_point_metrics(
    real: Tensor,
    gen: Tensor,
    compute_expensive: bool = True,
    checkerboard_config: Optional[Dict] = None,
) -> Dict[str, float]:
    """
    Compute all point cloud metrics.

    Args:
        real: (N, D) real samples
        gen: (M, D) generated samples
        compute_expensive: If True, compute coverage/density (slower)
        checkerboard_config: If provided, compute checkerboard metrics.
            Should contain keys: domain, cell_size, parity, lam, mu

    Returns:
        Dictionary of metrics including:
        - real_mean_x, real_mean_y: Mean of real samples
        - gen_mean_x, gen_mean_y: Mean of generated samples
        - real_std, gen_std: Standard deviation
        - wasserstein_2d: Sliced 2D Wasserstein distance
        - wasserstein_x, wasserstein_y: Per-dimension Wasserstein-2
        - mmd_rbf: RBF kernel MMD
        - mmd_multiscale: Multi-scale MMD
        - coverage, density: k-NN based metrics (if compute_expensive)
        - BV, JS_cell, WED, WED_norm, CQS: Checkerboard metrics (if checkerboard_config)

    Example
    -------
    >>> metrics = compute_point_metrics(real_samples, gen_samples)
    >>> print(f"W2: {metrics['wasserstein_2d']:.4f}, MMD: {metrics['mmd_rbf']:.4f}")
    
    >>> # With checkerboard metrics
    >>> cb_config = {"domain": (-4, 4, -4, 4), "cell_size": 1.0, "parity": 0}
    >>> metrics = compute_point_metrics(real, gen, checkerboard_config=cb_config)
    >>> print(f"CQS: {metrics['CQS']:.4f}")
    """
    real_np = real.cpu().numpy()
    gen_np = gen.cpu().numpy()

    metrics: Dict[str, float] = {}

    # Basic statistics
    metrics["real_mean_x"] = float(real_np[:, 0].mean())
    metrics["real_mean_y"] = (
        float(real_np[:, 1].mean()) if real_np.shape[1] > 1 else 0.0
    )
    metrics["gen_mean_x"] = float(gen_np[:, 0].mean())
    metrics["gen_mean_y"] = float(gen_np[:, 1].mean()) if gen_np.shape[1] > 1 else 0.0

    metrics["real_std"] = float(real_np.std())
    metrics["gen_std"] = float(gen_np.std())

    # Wasserstein distance
    if real_np.shape[1] == 2:
        # Always compute sliced W2 (fast approximation)
        metrics["swd_2d"] = sliced_wasserstein_2d(real_np, gen_np)
        # Compute exact W2 if POT available
        if POT_AVAILABLE:
            metrics["wasserstein_2d"] = wasserstein_2d_exact(real_np, gen_np)
        else:
            metrics["wasserstein_2d"] = metrics["swd_2d"]  # fallback to SWD
    metrics["wasserstein_x"] = wasserstein_1d_w2(real_np[:, 0], gen_np[:, 0])
    if real_np.shape[1] > 1:
        metrics["wasserstein_y"] = wasserstein_1d_w2(real_np[:, 1], gen_np[:, 1])

    # MMD with median heuristic for bandwidth
    metrics["mmd_rbf"] = compute_mmd(real, gen, kernel="rbf")

    # Multi-scale MMD (more robust)
    metrics["mmd_multiscale"] = compute_mmd_multiscale(real, gen)

    # Coverage and density (can be slow for large datasets)
    if compute_expensive and len(real) > 10 and len(gen) > 10:
        try:
            coverage, density = compute_coverage_density(real, gen)
            metrics["coverage"] = coverage
            metrics["density"] = density
        except Exception:
            metrics["coverage"] = -1.0
            metrics["density"] = -1.0
    
    # Checkerboard-specific metrics
    if checkerboard_config is not None:
        try:
            cb_metrics = compute_checkerboard_metrics(
                X_real=real_np,
                X_gen=gen_np,
                domain=checkerboard_config.get("domain", (-4.0, 4.0, -4.0, 4.0)),
                cell_size=checkerboard_config.get("cell_size", 1.0),
                parity=checkerboard_config.get("parity", 0),
                alpha=checkerboard_config.get("alpha", 1e-6),
                min_points_cell=checkerboard_config.get("min_points_cell", 5),
                max_points_cell=checkerboard_config.get("max_points_cell", None),
                lam=checkerboard_config.get("lam", 1.0),
                mu=checkerboard_config.get("mu", 1.0),
            )
            metrics.update(cb_metrics)
        except Exception as e:
            print(f"[WARNING] Checkerboard metrics computation failed: {e}")

    return metrics


